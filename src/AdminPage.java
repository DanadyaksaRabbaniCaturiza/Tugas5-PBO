    private void jButtonDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteActionPerformed
        // TODO add your handling code here:
        int barisDipilih = jTableDaftarBuku.getSelectedRow();       
        int idBuku = Integer.parseInt(jTableDaftarBuku.getValueAt(barisDipilih, 0).toString());
        DefaultTableModel  model = (DefaultTableModel) jTableDaftarBuku.getModel();
        
        Connection con = MyConnection.getConnection();
        try {          
            String sqlDeleteData = "DELETE FROM buku WHERE buku_id = ?";
            PreparedStatement statementDeleteData = con.prepareStatement(sqlDeleteData);
            statementDeleteData.setInt(1, idBuku);
            
            int berhasilDeleteData = statementDeleteData.executeUpdate();
            
            if (berhasilDeleteData > 0) {
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus!", "Message", JOptionPane.INFORMATION_MESSAGE);
                model.setRowCount(0);
                tampilDaftarBuku();
                jTextFieldJudul.setText("");
                jTextFieldPengarang.setText("");
                jTextFieldPenerbit.setText("");
                jTextFieldTahun.setText("");
                jComboBoxKategori.setSelectedItem("Pilih Kategori"); 
                jTextFieldJumlah.setText("");       
            }
        
        } catch (SQLException ex) {           
         System.err.print("gagal delete buku: " + ex.getMessage());
         JOptionPane.showMessageDialog(this, "gagal delete data!", "Message", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButtonDeleteActionPerformed

