    private void tampilDaftarBuku() {
                
        DefaultTableModel  model = (DefaultTableModel) jTableDaftarBuku.getModel(); 
        model.setColumnCount(0);
        model.addColumn("ID");
        model.addColumn("Judul");
        model.addColumn("Pengarang");
        model.addColumn("Penerbit");
        model.addColumn("Tahun");
        model.addColumn("Kategori");
        model.addColumn("Jumlah");
     
        Connection con = MyConnection.getConnection();
        
        try {
            String sqlListBuku = "SELECT buku_id, judul, pengarang, penerbit, tahun_terbit, kategori, jumlah FROM buku";
            PreparedStatement statementListBuku = con.prepareStatement(sqlListBuku);
            ResultSet resListBuku = statementListBuku.executeQuery();
            
            while (resListBuku.next()) {
               model.addRow(new Object[]{
                   resListBuku.getInt("buku_id"),
                   resListBuku.getString("judul"),
                   resListBuku.getString("pengarang"),
                   resListBuku.getString("penerbit"),
                   resListBuku.getInt("tahun_terbit"),
                   resListBuku.getString("kategori"),
                   resListBuku.getInt("jumlah"),
               }); 
            }
            
            String sqlListKategoriBuku = "SELECT DISTINCT kategori FROM buku WHERE kategori IS NOT NULL ORDER BY kategori ASC";
            PreparedStatement statementListKategoriBuku = con.prepareStatement(sqlListKategoriBuku);
            ResultSet resListKategoriBuku = statementListKategoriBuku.executeQuery();
            
            jComboBoxKategori.removeAllItems();
            jComboBoxKategori.addItem("Pilih Kategori");
            
            while(resListKategoriBuku.next()){
            jComboBoxKategori.addItem(resListKategoriBuku.getString("kategori"));
            }
            
        } catch (SQLException ex) {
            System.err.print("gagal memuat buku: " + ex.getMessage());
            JOptionPane.showMessageDialog(this, "Gagal memuat data ke sistem: " + ex.getMessage(), "Message", JOptionPane.INFORMATION_MESSAGE);
        }
    }
