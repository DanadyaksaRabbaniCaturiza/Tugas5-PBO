    private void jButtonPinjamBukuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPinjamBukuActionPerformed
        // TODO add your handling code here:
   
        String bukuDipilih = (String) jComboBoxBukuTersedia.getSelectedItem();
        String userName = jLabelUsernameUserPage.getText();        
     
        if (bukuDipilih.isEmpty() || jTextFieldJumlahBuku.getText().isEmpty() || jDateChooserKembali.getDate() == null) {
        JOptionPane.showMessageDialog(this, "Semua field harus diisi!", "Message", JOptionPane.INFORMATION_MESSAGE);
        return;
        }
        
        SimpleDateFormat formatTanggal = new SimpleDateFormat("yyyy-MM-dd");
        String tanggalKembali = formatTanggal.format(jDateChooserKembali.getDate());
        String tanggalPinjam = formatTanggal.format(new Date());                
        
        if (!jTextFieldJumlahBuku.getText().matches("\\d+")) {
        JOptionPane.showMessageDialog(this, "Jumlah buku harus berupa angka!", "Message", JOptionPane.INFORMATION_MESSAGE);
        return;
        }
        
        int jumlahBukuDipinjam = Integer.parseInt(jTextFieldJumlahBuku.getText().trim());
  
        if (jumlahBukuDipinjam == 0) {
        JOptionPane.showMessageDialog(this, "Jumlah buku harus lebih dari 0!", "Message", JOptionPane.INFORMATION_MESSAGE);
        return;
        }
        
        Connection con = MyConnection.getConnection();

        int jumlahBukuTersedia; 
        int idUser = -1;
        int idBuku = -1;
        
        try {
            
            String sqlJumlahBuku = "SELECT jumlah FROM buku WHERE judul = ?";   
            PreparedStatement jumlahBukuStmt = con.prepareStatement(sqlJumlahBuku);
            jumlahBukuStmt.setString(1, bukuDipilih);
            ResultSet resJumlahBuku = jumlahBukuStmt.executeQuery();
            
            if (resJumlahBuku.next()) {               
               jumlahBukuTersedia = resJumlahBuku.getInt("jumlah");
                
                if (jumlahBukuDipinjam > jumlahBukuTersedia) {                   
                 JOptionPane.showMessageDialog(this, "stok buku tidak cukup", "Message", JOptionPane.INFORMATION_MESSAGE);
                 return;                
                }               
            } 
            
            String sqlGetUserId = "SELECT user_id FROM users WHERE username = ?";
            PreparedStatement statementGetUserId = con.prepareStatement(sqlGetUserId);
            statementGetUserId.setString(1, userName);

            ResultSet resGetUserId = statementGetUserId.executeQuery();            

            if (resGetUserId.next()) {
               idUser = resGetUserId.getInt("user_id");
            }
            
            String sqlGetBukuId = "SELECT buku_id FROM buku WHERE judul = ?";
            PreparedStatement statementGetBukuId = con.prepareStatement(sqlGetBukuId);
            statementGetBukuId.setString(1, bukuDipilih);
            
            ResultSet resGetBukuId = statementGetBukuId.executeQuery();
            
            if(resGetBukuId.next()){
                idBuku = resGetBukuId.getInt("buku_id");
            }
            
            if (idUser != -1 && idBuku != -1) {
                String sqlAddPinjaman = "INSERT INTO peminjaman (user_id, buku_id, tanggal_pinjam, tanggal_kembali) VALUES (?, ?, ?, ?)";       
                PreparedStatement statementAddPinjaman = con.prepareStatement(sqlAddPinjaman);
                
                statementAddPinjaman.setInt(1,idUser);
                statementAddPinjaman.setInt(2,idBuku);
                statementAddPinjaman.setDate(3,java.sql.Date.valueOf(tanggalPinjam));
                statementAddPinjaman.setDate(4,java.sql.Date.valueOf(tanggalKembali));
                
                int berhasilAddPinjaman = statementAddPinjaman.executeUpdate();
                
                if (berhasilAddPinjaman > 0) {                    
                    String sqlUpdateJumlahBuku = "UPDATE buku SET jumlah = (jumlah-?) WHERE buku_id = ?";
                    PreparedStatement statementUpdateJumlahBuku = con.prepareStatement(sqlUpdateJumlahBuku);
                    
                    statementUpdateJumlahBuku.setInt(1, jumlahBukuDipinjam);
                    statementUpdateJumlahBuku.setInt(2, idBuku);
                    
                    int berhasilUpdateJumlahBuku = statementUpdateJumlahBuku.executeUpdate();
                    
                    if (berhasilUpdateJumlahBuku > 0) {                       
                        JOptionPane.showMessageDialog(this, "Buku Berhasil Dipinjam!", "Message", JOptionPane.INFORMATION_MESSAGE);                  
                    
                        tampilJudulBukuComboBox(); 
                    
                        jTextFieldJumlahBuku.setText("");
                        jDateChooserKembali.setDate(null);

                    }               
                }
            }
            
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Gagal memproses peminjaman buku!", "Message", JOptionPane.INFORMATION_MESSAGE);
        }             
    }//GEN-LAST:event_jButtonPinjamBukuActionPerformed

