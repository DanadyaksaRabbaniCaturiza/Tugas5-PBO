    private void tampilJudulBukuComboBox () {
        Connection con = MyConnection.getConnection();
        String sqlListBuku = "SELECT judul FROM buku";
        
        try {
            PreparedStatement listBuku = con.prepareStatement(sqlListBuku);
            ResultSet resListBuku = listBuku.executeQuery();
            
            while (resListBuku.next()) {
                jComboBoxBukuTersedia.addItem(resListBuku.getString("judul"));
            }
            
        } catch (SQLException ex) {
            System.err.print("gagal memuat buku: " + ex.getMessage());
            JOptionPane.showMessageDialog(this, "gagal mendapat daftar buku", "Message", JOptionPane.INFORMATION_MESSAGE);

        }
    }
